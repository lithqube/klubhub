// ReconciliationReason is the reason a finance_entry_reconciliations row was
// raised. Surfaced back to clients so the UI can render the right prompt.
type ReconciliationReason string

const (
	ReconciliationReasonFeeChanged      ReconciliationReason = "fee_changed"
	ReconciliationReasonCurrencyChanged ReconciliationReason = "currency_changed"
	ReconciliationReasonPaymentReversed ReconciliationReason = "payment_reversed"
)

// ReconciliationAction is the user-visible choice attached to a decision.
type ReconciliationAction string

const (
	ReconciliationActionUpdate ReconciliationAction = "update"
	ReconciliationActionDelete ReconciliationAction = "delete"
	ReconciliationActionVoid   ReconciliationAction = "void"
	ReconciliationActionKeep   ReconciliationAction = "keep"
)

// ReconciliationStatus is the lifecycle of a finance_entry_reconciliations
// row.
type ReconciliationStatus string

const (
	ReconciliationStatusPending  ReconciliationStatus = "pending"
	ReconciliationStatusResolved ReconciliationStatus = "resolved"
)

// EntryReconciliation is the durable decision for one (gig, finance entry)
// snapshot, created by the transition processor and resolved by the UI.
type EntryReconciliation struct {
	ID               uuid.UUID              `json:"id"`
	GigID            uuid.UUID              `json:"gig_id"`
	EntryID          uuid.UUID              `json:"entry_id"`
	Reason           ReconciliationReason  `json:"reason"`
	AllowedActions   []ReconciliationAction `json:"allowed_actions"`
	GigAmountMinor   int64                  `json:"gig_amount_minor"`
	GigCurrency      string                 `json:"gig_currency"`
	GigPaymentStatus gig.PaymentStatus      `json:"gig_payment_status"`
	EntryUpdatedAt   time.Time              `json:"entry_updated_at"`
	Status           ReconciliationStatus   `json:"status"`
	Resolution       ReconciliationAction   `json:"resolution,omitempty"`
	CreatedAt        time.Time              `json:"created_at"`
	UpdatedAt        time.Time              `json:"updated_at"`
	ResolvedAt       *time.Time             `json:"resolved_at,omitempty"`
}

// ResolveReconciliationRequest is the body of POST /reconciliations/{id}/resolve.
type ResolveReconciliationRequest struct {
	Action    ReconciliationAction `json:"action"`
	UpdatedAt time.Time            `json:"updated_at"`
}

// FinanceEntryColumns is the projection used for the active-generated-entry
// lookup and the freshly-created row.
const financeEntryColumns = `id, kind, amount_minor, currency, category, entry_date::text, description, notes,
gig_id, status, auto_generated, source_kind, source_id, source_amount_minor, source_currency,
source_description, created_at, updated_at, deleted_at`

func scanFinanceEntry(e *Entry) []any {
	return []any{&e.ID, &e.Kind, &e.AmountMinor, &e.Currency, &e.Category, &e.EntryDate,
		&e.Description, &e.Notes, &e.GigID, &e.Status, &e.AutoGenerated, &e.SourceKind,
		&e.SourceID, &e.SourceAmountMinor, &e.SourceCurrency, &e.SourceDescription,
		&e.CreatedAt, &e.UpdatedAt, &e.DeletedAt}
}

// reconciliationColumns is the projection used to read a pending row back
// out of the database. The COALESCE keeps the row scannable while the
// resolution column is still NULL.
const reconciliationColumns = `id, gig_id, entry_id, reason, allowed_actions, gig_amount_minor,
gig_currency, gig_payment_status, entry_updated_at, status, COALESCE(resolution,''),
created_at, updated_at, resolved_at`

func scanReconciliation(r *EntryReconciliation) []any {
	return []any{&r.ID, &r.GigID, &r.EntryID, &r.Reason, &r.AllowedActions, &r.GigAmountMinor,
		&r.GigCurrency, &r.GigPaymentStatus, &r.EntryUpdatedAt, &r.Status, &r.Resolution,
		&r.CreatedAt, &r.UpdatedAt, &r.ResolvedAt}
}

// Sentinel errors exposed to the API layer.
var (
	ErrReconciliationNotFound = errors.New("finance entry reconciliation not found")
	ErrReconciliationConflict = errors.New("finance entry reconciliation changed; refresh and retry")
	ErrReconciliationAction   = errors.New("reconciliation action is not allowed")
)

// GigPaymentTransitionProcessor is the shared finance implementation wired
// into both the gig repository's UpdateWithPaymentTransition path and the
// invoice-payment sync path. Running both writes through a single processor
// is what guarantees one active generated income row per gig: idempotency
// is enforced by (source_kind, source_id, kind) plus the matching
// reconciliation row.
type GigPaymentTransitionProcessor struct {
	pool *pgxpool.Pool
}

// NewGigPaymentTransitionProcessor returns a processor backed by pool.
func NewGigPaymentTransitionProcessor(pool *pgxpool.Pool) *GigPaymentTransitionProcessor {
	return &GigPaymentTransitionProcessor{pool: pool}
}

// ProcessGigPaymentTransition is the contract declared in
// gig.PaymentTransitionProcessor. When db is nil the processor runs in its
// own transaction so callers like invoice-payment sync can opt out of
// sharing the parent write's tx.
func (p *GigPaymentTransitionProcessor) ProcessGigPaymentTransition(ctx context.Context, db gig.PaymentTransitionTx, before, after gig.PaymentSnapshot) (*gig.PaymentReconciliationMetadata, error) {
	if db != nil {
		return p.process(ctx, db, before, after)
	}
	var metadata *gig.PaymentReconciliationMetadata
	err := pgx.BeginTxFunc(ctx, p.pool, pgx.TxOptions{}, func(tx pgx.Tx) error {
		var inner error
		metadata, inner = p.process(ctx, tx, before, after)
		return inner
	})
	return metadata, err
}

func (p *GigPaymentTransitionProcessor) process(ctx context.Context, db gig.PaymentTransitionTx, before, after gig.PaymentSnapshot) (*gig.PaymentReconciliationMetadata, error) {
	amountMinor, err := gigFeeToMinor(after.FeeAmount)
	if err != nil {
		return nil, err
	}
	currency := strings.ToUpper(after.FeeCurrency)
	if !isCurrencyCode(currency) {
		return nil, EntryValidationErrors{{Field: "fee_currency", Message: "must be an uppercase 3-letter code"}}
	}

	entry, err := getActiveGeneratedGigIncome(ctx, db, after.GigID)
	if err != nil && !errors.Is(err, ErrEntryNotFound) {
		return nil, err
	}
	becamePaid := before.PaymentStatus != gig.PaymentStatusPaid && after.PaymentStatus == gig.PaymentStatusPaid
	leftPaid := before.PaymentStatus == gig.PaymentStatusPaid && after.PaymentStatus != gig.PaymentStatusPaid

	if becamePaid && (entry == nil || errors.Is(err, ErrEntryNotFound)) {
		if _, err := createGeneratedGigIncome(ctx, db, after, amountMinor, currency); err != nil {
			return nil, err
		}
		// Any pending prompt for this gig is now stale: the gig's fee at
		// the moment of paid transition became the entry's source. Mark
		// it acknowledged so the same prompt does not recur.
		if err := resolvePendingAsAcknowledged(ctx, db, after.GigID); err != nil {
			return nil, err
		}
		return nil, nil
	}
	if entry == nil {
		return nil, nil
	}

	var reason ReconciliationReason
	switch {
	case leftPaid:
		reason = ReconciliationReasonPaymentReversed
	case entry.SourceCurrency != nil && *entry.SourceCurrency != currency:
		reason = ReconciliationReasonCurrencyChanged
	case entry.SourceAmountMinor != nil && *entry.SourceAmountMinor != amountMinor:
		reason = ReconciliationReasonFeeChanged
	default:
		// Nothing changed about the snapshot the user was originally
		// prompted for; just refresh the acknowledged state.
		if err := resolvePendingAsAcknowledged(ctx, db, after.GigID); err != nil {
			return nil, err
		}
		return nil, nil
	}

	decision, err := upsertPendingReconciliation(ctx, db, entry, after, amountMinor, currency, reason)
	if err != nil {
		return nil, err
	}
	actions := make([]string, len(decision.AllowedActions))
	for i, action := range decision.AllowedActions {
		actions[i] = string(action)
	}
	return &gig.PaymentReconciliationMetadata{
		ID:             decision.ID,
		EntryID:        decision.EntryID,
		Reason:         string(decision.Reason),
		AllowedActions: actions,
		UpdatedAt:      decision.UpdatedAt,
	}, nil
}

// ErrGigFeeMinorUnitPrecision is returned when a gig fee carries more
// than two decimal places, since finance stores money in integer minor
// units.
var ErrGigFeeMinorUnitPrecision = errors.New("gig fee must have at most two decimal places")

// gigFeeToMinor converts a gig fee (decimal major units) into integer
// minor units. The gig table stores DECIMAL(12,2); we accept up to two
// fractional digits and reject anything finer so we never silently
// truncate user money.
func gigFeeToMinor(value decimal.Decimal) (int64, error) {
	if !value.IsPositive() {
		return 0, ErrGigFeeMinorUnitPrecision
	}
	// shopspring/decimal exposes Exponent(); bail out on more than 2
	// fractional digits.
	if value.Exponent() < -2 {
		return 0, ErrGigFeeMinorUnitPrecision
	}
	return value.Mul(decimal.NewFromInt(100)).BigInt().Int64(), nil
}

// getActiveGeneratedGigIncome returns the single active auto-generated
// income row linked to gigID, or ErrEntryNotFound. The unique partial
// index on (source_kind, source_id, kind) where auto_generated=true and
// status='active' guarantees at most one row.
func getActiveGeneratedGigIncome(ctx context.Context, db gig.PaymentTransitionTx, gigID uuid.UUID) (*Entry, error) {
	var e Entry
	err := db.QueryRow(ctx, `SELECT `+financeEntryColumns+` FROM finance_entries
		WHERE auto_generated=true AND status='active' AND deleted_at IS NULL AND gig_id=$1
		ORDER BY created_at DESC LIMIT 1`, gigID).Scan(scanFinanceEntry(&e)...)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, ErrEntryNotFound
	}
	if err != nil {
		return nil, err
	}
	return &e, nil
}

// createGeneratedGigIncome idempotently inserts the auto-generated
// income row. The (source_kind, source_id, kind) partial unique index
// guarantees at most one active row per gig. On a conflict we look the
// existing row up and return it when the payload matches (idempotent
// retry); otherwise we surface ErrGeneratedEntryConflict so the caller
// can decide whether to update the existing row via the reconciliation
// flow or void it.
func createGeneratedGigIncome(ctx context.Context, db gig.PaymentTransitionTx, snap gig.PaymentSnapshot, amountMinor int64, currency string) (*Entry, error) {
	date := snap.Date.Format("2006-01-02")
	description := gigLineDescription(snap.EventName, snap.Venue, "", date)
	gigID := snap.GigID
	sourceDesc := "gig:" + gigID.String()
	sourceAmount := amountMinor
	sourceCurrency := currency

	// Probe first. The (source_kind, source_id, kind) partial unique
	// index only covers active, not-deleted rows; an existing voided
	// or deleted row would otherwise let this INSERT silently create a
	// fresh active replacement. An existing active row with a
	// matching payload is reused (idempotent replay); an active row
	// with a mismatched payload is a hard conflict (same source, new
	// numbers — must go through the reconciliation flow).
	var existing Entry
	err := db.QueryRow(ctx, `SELECT `+financeEntryColumns+` FROM finance_entries
		WHERE auto_generated=true AND source_kind='gig_payment' AND source_id=$1 AND kind='income'
		  AND deleted_at IS NULL
		ORDER BY created_at DESC LIMIT 1`, gigID).Scan(scanFinanceEntry(&existing)...)
	if err == nil {
		if existing.Status == EntryStatusActive && existing.DeletedAt == nil {
			if existing.AmountMinor != amountMinor || existing.Currency != currency ||
				existing.EntryDate != date || existing.Description != description ||
				existing.SourceAmountMinor == nil || *existing.SourceAmountMinor != sourceAmount ||
				existing.SourceCurrency == nil || *existing.SourceCurrency != sourceCurrency ||
				existing.SourceDescription != sourceDesc {
				return nil, ErrGeneratedEntryConflict
			}
			return &existing, nil
		}
		// Voided/deleted prior row: the gig has been re-paid; INSERT a
		// fresh active row to replace it.
	} else if !errors.Is(err, pgx.ErrNoRows) {
		return nil, err
	}

	var e Entry
	err = db.QueryRow(ctx, `INSERT INTO finance_entries
		(kind, amount_minor, currency, category, entry_date, description, notes, gig_id,
		 auto_generated, source_kind, source_id, source_amount_minor, source_currency, source_description)
		VALUES ('income', $1, $2, 'gig_fee', $3::date, $4, '', $5,
		 true, 'gig_payment', $6, $7, $8, $9)
		RETURNING `+financeEntryColumns,
		amountMinor, currency, date, description, gigID,
		gigID, sourceAmount, sourceCurrency, sourceDesc).Scan(scanFinanceEntry(&e)...)
	if err == nil {
		return &e, nil
	}
	if !isUniqueViolation(err) {
		if isEntryGigFKViolation(err) {
			return nil, EntryValidationErrors{{Field: "gig_id", Message: "does not reference an existing gig"}}
		}
		return nil, err
	}
	// The partial index tripped because a concurrent writer just
	// inserted the same source. Re-read and reuse the matching row.
	err = db.QueryRow(ctx, `SELECT `+financeEntryColumns+` FROM finance_entries
		WHERE auto_generated=true AND source_kind='gig_payment' AND source_id=$1 AND kind='income'
		  AND status='active' AND deleted_at IS NULL`,
		gigID).Scan(scanFinanceEntry(&existing)...)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, ErrGeneratedEntryConflict
	}
	if err != nil {
		return nil, err
	}
	if existing.AmountMinor != amountMinor || existing.Currency != currency ||
		existing.EntryDate != date || existing.Description != description ||
		existing.SourceAmountMinor == nil || *existing.SourceAmountMinor != sourceAmount ||
		existing.SourceCurrency == nil || *existing.SourceCurrency != sourceCurrency ||
		existing.SourceDescription != sourceDesc {
		return nil, ErrGeneratedEntryConflict
	}
	return &existing, nil
}

// resolvePendingAsAcknowledged transitions every pending reconciliation
// row for gigID to resolved with no resolution code. This is used after a
// paid transition or when the snapshot the prompt was raised against no
// longer differs from the current gig — the user effectively answered by
// doing nothing (the entry already matches).
func resolvePendingAsAcknowledged(ctx context.Context, db gig.PaymentTransitionTx, gigID uuid.UUID) error {
	_, err := db.Exec(ctx, `UPDATE finance_entry_reconciliations
		SET status='resolved', resolution='keep', resolved_at=clock_timestamp(), updated_at=clock_timestamp()
		WHERE gig_id=$1 AND status='pending'`, gigID)
	if err != nil {
		return err
	}
	return nil
}

// upsertPendingReconciliation creates one pending decision per gig (the
// partial unique index guarantees that) or refreshes the existing one
// with the latest snapshot so the UI sees the most recent fee/currency.
func upsertPendingReconciliation(ctx context.Context, db gig.PaymentTransitionTx, entry *Entry, snap gig.PaymentSnapshot, amountMinor int64, currency string, reason ReconciliationReason) (*EntryReconciliation, error) {
	actions := allowedActionsFor(reason)
	var out EntryReconciliation
	err := db.QueryRow(ctx, `INSERT INTO finance_entry_reconciliations
		(gig_id, entry_id, reason, allowed_actions, gig_amount_minor, gig_currency, gig_payment_status, entry_updated_at, status)
		VALUES ($1, $2, $3, $4, $5, $6, $7, $8, 'pending')
		ON CONFLICT (gig_id) WHERE status='pending'
		DO UPDATE SET
		  reason = EXCLUDED.reason,
		  allowed_actions = EXCLUDED.allowed_actions,
		  gig_amount_minor = EXCLUDED.gig_amount_minor,
		  gig_currency = EXCLUDED.gig_currency,
		  gig_payment_status = EXCLUDED.gig_payment_status,
		  entry_updated_at = EXCLUDED.entry_updated_at,
		  updated_at = clock_timestamp()
		RETURNING `+reconciliationColumns,
		snap.GigID, entry.ID, reason, actions, amountMinor, currency, snap.PaymentStatus, entry.UpdatedAt,
	).Scan(scanReconciliation(&out)...)
	if err != nil {
		return nil, err
	}
	return &out, nil
}

// allowedActionsFor enforces the action/reason pair documented in the
// migration's allowed_actions CHECK constraint.
func allowedActionsFor(reason ReconciliationReason) []ReconciliationAction {
	switch reason {
	case ReconciliationReasonFeeChanged, ReconciliationReasonCurrencyChanged:
		return []ReconciliationAction{ReconciliationActionUpdate, ReconciliationActionKeep}
	case ReconciliationReasonPaymentReversed:
		return []ReconciliationAction{ReconciliationActionDelete, ReconciliationActionVoid, ReconciliationActionKeep}
	}
	return nil
}
