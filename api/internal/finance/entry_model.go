type DateRange struct {
	From string `json:"from"`
	To   string `json:"to"`
}

func (r DateRange) Validate() error {
	from, err := parseEntryDate(r.From)
	if err != nil {
		return EntryValidationErrors{{Field: "from", Message: "must be YYYY-MM-DD"}}
	}
	to, err := parseEntryDate(r.To)
	if err != nil {
		return EntryValidationErrors{{Field: "to", Message: "must be YYYY-MM-DD"}}
	}
	if !from.Before(to) {
		return EntryValidationErrors{{Field: "to", Message: "must be after from (exclusive upper bound)"}}
	}
	return nil
}

