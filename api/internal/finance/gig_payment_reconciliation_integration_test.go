func TestIntegration_ReconciliationHTTPGetAndResolve(t *testing.T) {
	resetGigPaymentReconciliationState(t)
	processor := NewGigPaymentTransitionProcessor(testPool)
	svc, created := createTransitionGig(t, processor, "80.00", "EUR")
	paid := gig.PaymentStatusPaid
	current := updateTransitionGig(t, svc, created, func(u *gig.GigUpdate) { u.PaymentStatus = &paid })
	fee := decimal.RequireFromString("90.00")
	_ = updateTransitionGig(t, svc, current, func(u *gig.GigUpdate) { u.FeeAmount = &fee })

	h := NewEntryHandler(NewEntryService(NewEntryRepository(testPool)))
	get := httptest.NewRecorder()
	h.ServeHTTP(get, httptest.NewRequest(http.MethodGet, "/api/v1/finance/reconciliations?gig_id="+created.ID.String(), nil))
	if get.Code != http.StatusOK || !strings.Contains(get.Body.String(), `"reason":"fee_changed"`) {
		t.Fatalf("GET reconciliation: status=%d body=%s", get.Code, get.Body.String())
	}
	decision, err := NewEntryService(NewEntryRepository(testPool)).GetPendingReconciliationByGig(context.Background(), created.ID)
	if err != nil {
		t.Fatal(err)
	}
	body := `{"action":"keep","updated_at":"` + decision.UpdatedAt.Format(time.RFC3339Nano) + `"}`
	resolve := httptest.NewRecorder()
	h.ServeHTTP(resolve, httptest.NewRequest(http.MethodPost, "/api/v1/finance/reconciliations/"+decision.ID.String()+"/resolve", strings.NewReader(body)))
	if resolve.Code != http.StatusOK || !strings.Contains(resolve.Body.String(), `"resolution":"keep"`) {
		t.Fatalf("resolve reconciliation: status=%d body=%s", resolve.Code, resolve.Body.String())
	}
	refresh := httptest.NewRecorder()
	h.ServeHTTP(refresh, httptest.NewRequest(http.MethodGet, "/api/v1/finance/reconciliations?gig_id="+created.ID.String(), nil))
	if refresh.Code != http.StatusNotFound {
		t.Fatalf("resolved refresh status=%d body=%s", refresh.Code, refresh.Body.String())
	}
}
