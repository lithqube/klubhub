func TestIntegration_InvoicePaymentSyncUsesSameTransitionProcessorWithoutDuplicates(t *testing.T) {
	resetGigPaymentReconciliationState(t)
	t.Cleanup(func() {
		// Don't leave billing_profiles seeded — subsequent tests in
		// the package (e.g. TestIntegration_GetSeedsEmptyRow) expect
		// a clean slate so they can assert the seed semantics.
		_, _ = testPool.Exec(context.Background(), `DELETE FROM billing_profiles`)
	})
	ctx := context.Background()
	setBillingProfile(t, nil)
	invoiceSvc := newTestInvoiceService()
	processor := NewGigPaymentTransitionProcessor(testPool)
	paySvc := NewPaymentService(NewPaymentRepositoryWithTransitionProcessor(testPool, processor))
	gigID := insertTestGig(t, "EUR")
	draft := issuableDraft(t, invoiceSvc, gigID, "HOOK", nil)
	issued, err := invoiceSvc.Issue(ctx, draft.ID, IssueInvoiceRequest{UpdatedAt: draft.UpdatedAt})
	if err != nil {
		t.Fatal(err)
	}
	payment, err := paySvc.Create(ctx, issued.ID, CreatePaymentRequest{Currency: "EUR", AmountMinor: issued.NetPayableMinor, Kind: PaymentKindPayment})
	if err != nil {
		t.Fatal(err)
	}
	completed, err := paySvc.Update(ctx, payment.ID, UpdatePaymentRequest{Status: PaymentStatusCompleted, UpdatedAt: payment.UpdatedAt})
	if err != nil {
		t.Fatal(err)
	}
	if entry := activeGeneratedIncome(t, gigID); entry.AmountMinor != 25000 || entry.Currency != "EUR" {
		t.Fatalf("invoice-driven entry = %+v", entry)
	}
	// Replaying completed status goes through sync again but cannot duplicate revenue.
	if _, err := paySvc.Update(ctx, payment.ID, UpdatePaymentRequest{Status: PaymentStatusCompleted, UpdatedAt: completed.UpdatedAt}); err != nil {
		t.Fatal(err)
	}
	if got := generatedIncomeCount(t, gigID, true); got != 1 {
		t.Fatalf("active generated income count = %d, want 1", got)
	}
}

